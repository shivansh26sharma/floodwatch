"""
Download REAL data for the study region.

    python -m src.data.download                 # full 2010-2019 pull
    python -m src.data.download --start 2016-01-01 --end 2019-12-31
    python -m src.data.download --force         # ignore cached files

WHAT THIS FETCHES, AND WHAT IT IS
---------------------------------
Three things, all free and with no registration:

  rainfall   ERA5 daily precipitation, via the Open-Meteo archive API
  river      GloFAS daily river discharge, via the Open-Meteo flood API
  terrain    Elevation samples, via the Open-Meteo elevation API, from
             which slope and ruggedness are derived here

BE PRECISE ABOUT THIS IN YOUR REPORT. ERA5 and GloFAS are *reanalysis*
products: physics-based models that assimilate large volumes of real
observations (surface stations, satellites, radiosondes) to produce a
gridded, gap-free record. They are real data in the sense that matters —
not synthetic, not generated by us — and they are standard inputs in
published hydrology and flood research.

They are NOT IMD station gauges. ERA5 is ~25 km resolution, so it smooths
local extremes, and it will systematically under-represent the peak
intensity of an event like Kerala 2018. GloFAS discharge is modelled
routing, not a stage reading at a CWC gauge.

Write that distinction down. Claiming station observations when you used
reanalysis is the kind of thing an examiner catches, and the honest version
is perfectly defensible: reanalysis is what you use when you need a
consistent, gap-free, reproducible record across a whole region.

The upgrade path is unchanged: implement the IMD and WRIS branches in
loaders.py and the rest of the pipeline does not move.

PROVENANCE
----------
Every run writes data/raw/provenance.json recording each source, its URL,
the exact parameters requested, the retrieval timestamp and row counts.
That file is your dataset lineage section — do not delete it.

ATTRIBUTION
-----------
Open-Meteo is free for non-commercial use and asks to be credited. ERA5 is
Copernicus Climate Change Service information; GloFAS is part of the
Copernicus Emergency Management Service. Cite all three.
"""

import argparse
import json
import ssl
import time
import urllib.parse
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd

from src.config import CFG, ROOT
from src.data import districts as dref
from src.data.districts import TERRAIN_SAMPLE_OFFSET_DEG

ARCHIVE_URL = "https://archive-api.open-meteo.com/v1/archive"
FLOOD_URL = "https://flood-api.open-meteo.com/v1/flood"
ELEVATION_URL = "https://api.open-meteo.com/v1/elevation"

USER_AGENT = "FloodWatch/1.0 (student research project)"

# TLS trust store.
# Python installed from python.org (and most standalone builds) does NOT use
# the macOS keychain, so urllib has no CA certificates and every HTTPS call
# dies with "CERTIFICATE_VERIFY_FAILED: unable to get local issuer
# certificate". certifi ships Mozilla's CA bundle, so we point at that
# explicitly and the script works the same on macOS, Linux and Windows.
#
# The alternative — running "Install Certificates.command" from your Python
# install — fixes it machine-wide but is easy to forget and impossible to
# reproduce on someone else's laptop. Doing it in code is reproducible.
#
# NEVER "fix" this by disabling verification (ssl._create_unverified_context
# or verify=False). That silently accepts any certificate.
try:
    import certifi
    SSL_CONTEXT = ssl.create_default_context(cafile=certifi.where())
except ImportError:  # pragma: no cover
    SSL_CONTEXT = ssl.create_default_context()
TIMEOUT = 90
RETRIES = 4
PAUSE_SECONDS = 1.2          # be polite to a free service


# ----------------------------------------------------------------------
# HTTP
# ----------------------------------------------------------------------

def fetch_json(url: str, params: dict) -> dict:
    """GET with retry and exponential backoff."""
    query = urllib.parse.urlencode(params, safe=",:")
    full = f"{url}?{query}"
    last = None

    for attempt in range(1, RETRIES + 1):
        try:
            req = urllib.request.Request(full, headers={"User-Agent": USER_AGENT})
            with urllib.request.urlopen(
                req, timeout=TIMEOUT, context=SSL_CONTEXT
            ) as resp:
                return json.loads(resp.read().decode())
        except Exception as exc:  # noqa: BLE001
            last = exc
            if attempt < RETRIES:
                wait = 2 ** attempt
                print(f"    attempt {attempt} failed ({exc}); retrying in {wait}s")
                time.sleep(wait)

    hint = (
        "If this is a network restriction, run this script on a machine with "
        "normal internet access — it only needs outbound HTTPS."
    )
    if "CERTIFICATE_VERIFY" in str(last):
        hint = (
            "Your Python has no CA bundle. Install certifi and retry:\n"
            "    pip install certifi\n"
            "On macOS you can also run the installer's certificate script:\n"
            "    /Applications/Python\\ 3.x/Install\\ Certificates.command\n"
            "Do NOT disable certificate verification to get past this."
        )
    raise RuntimeError(
        f"Failed after {RETRIES} attempts: {full}\nLast error: {last}\n{hint}"
    )


# ----------------------------------------------------------------------
# Sources
# ----------------------------------------------------------------------

def fetch_rainfall(districts: dict, start: str, end: str) -> pd.DataFrame:
    frames = []
    for name, (lat, lon) in districts.items():
        print(f"  rainfall  {name}")
        data = fetch_json(ARCHIVE_URL, {
            "latitude": lat, "longitude": lon,
            "start_date": start, "end_date": end,
            "daily": "precipitation_sum",
            "timezone": "Asia/Kolkata",
        })
        daily = data["daily"]
        frames.append(pd.DataFrame({
            "date": pd.to_datetime(daily["time"]),
            "district": name,
            "rainfall_mm": daily["precipitation_sum"],
        }))
        time.sleep(PAUSE_SECONDS)
    return pd.concat(frames, ignore_index=True)


def fetch_river(districts: dict, start: str, end: str) -> pd.DataFrame:
    """GloFAS river discharge (m3/s) at the grid cell containing each point.

    Discharge is not the same quantity as gauge stage (m), but it is the
    physically meaningful one for flooding and it is what GloFAS provides.
    The column is named river_discharge_m3s so nobody later mistakes it for
    a water level reading.
    """
    frames = []
    for name, (lat, lon) in districts.items():
        print(f"  discharge {name}")
        data = fetch_json(FLOOD_URL, {
            "latitude": lat, "longitude": lon,
            "start_date": start, "end_date": end,
            "daily": "river_discharge",
        })
        daily = data["daily"]
        frames.append(pd.DataFrame({
            "date": pd.to_datetime(daily["time"]),
            "district": name,
            "river_discharge_m3s": daily["river_discharge"],
        }))
        time.sleep(PAUSE_SECONDS)
    return pd.concat(frames, ignore_index=True)


def fetch_terrain(districts: dict) -> pd.DataFrame:
    """Elevation at a 5-point cross per district -> slope and ruggedness.

    Sampling centre plus four neighbours at +/- ~5.5 km lets us estimate a
    real terrain gradient instead of inventing one. Slope is the magnitude
    of the finite-difference gradient; ruggedness is the standard deviation
    of the five samples, which stands in for local relief.
    """
    d = TERRAIN_SAMPLE_OFFSET_DEG
    rows = []

    for name, (lat, lon) in districts.items():
        print(f"  terrain   {name}")
        pts = [(lat, lon), (lat + d, lon), (lat - d, lon),
               (lat, lon + d), (lat, lon - d)]
        data = fetch_json(ELEVATION_URL, {
            "latitude": ",".join(str(p[0]) for p in pts),
            "longitude": ",".join(str(p[1]) for p in pts),
        })
        elev = [float(e) for e in data["elevation"]]
        centre, north, south, east, west = elev

        # Metres per degree: ~111,320 N-S; scaled by cos(lat) E-W.
        import math
        m_per_deg_ns = 111_320.0
        m_per_deg_ew = 111_320.0 * math.cos(math.radians(lat))

        dz_dy = (north - south) / (2 * d * m_per_deg_ns)
        dz_dx = (east - west) / (2 * d * m_per_deg_ew)
        slope_deg = math.degrees(math.atan(math.hypot(dz_dx, dz_dy)))

        mean_elev = sum(elev) / len(elev)
        variance = sum((e - mean_elev) ** 2 for e in elev) / len(elev)
        ruggedness = variance ** 0.5

        rows.append({
            "district": name,
            "mean_elevation_m": round(centre, 1),
            "mean_slope_deg": round(slope_deg, 3),
            "terrain_ruggedness_m": round(ruggedness, 2),
            "lat": lat,
            "lon": lon,
            "state": dref.INDIA_FLOOD_DISTRICTS[name][2],
            "basin": dref.INDIA_FLOOD_DISTRICTS[name][3],
        })
        time.sleep(PAUSE_SECONDS)

    return pd.DataFrame(rows)


# ----------------------------------------------------------------------
# Orchestration
# ----------------------------------------------------------------------

def run(start: str | None = None, end: str | None = None,
        force: bool = False) -> dict[str, Path]:
    start = start or str(CFG.project.start_date)
    end = end or str(CFG.project.end_date)

    names = dref.selected()
    districts = dref.coords(names)

    raw = ROOT / "data/raw"
    raw.mkdir(parents=True, exist_ok=True)

    targets = {
        "rainfall": (raw / "rainfall_era5.csv", lambda: fetch_rainfall(districts, start, end)),
        "river":    (raw / "river_glofas.csv", lambda: fetch_river(districts, start, end)),
        "terrain":  (raw / "terrain_elevation.csv", lambda: fetch_terrain(districts)),
    }

    print(f"[download] region={CFG.project.region}  "
          f"districts={len(districts)}  {start} .. {end}")

    manifest, written = {}, {}
    for key, (path, fn) in targets.items():
        if path.exists() and not force:
            print(f"[download] {path.name} already present — skipping (--force to refetch)")
            df = pd.read_csv(path)
        else:
            df = fn()
            df.to_csv(path, index=False)
            print(f"[download] wrote {path.name}  ({len(df):,} rows)")

        written[key] = path
        manifest[key] = {
            "file": str(path.relative_to(ROOT)),
            "rows": int(len(df)),
            "retrieved_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        }

    manifest["rainfall"].update({
        "source": "ERA5 reanalysis via Open-Meteo archive API",
        "url": ARCHIVE_URL,
        "variable": "precipitation_sum (mm/day)",
        "nature": "reanalysis — NOT station observations",
        "citation": "Copernicus Climate Change Service (C3S) ERA5; data served by Open-Meteo.com",
    })
    manifest["river"].update({
        "source": "GloFAS river discharge via Open-Meteo flood API",
        "url": FLOOD_URL,
        "variable": "river_discharge (m3/s)",
        "nature": "modelled routing — NOT a gauge stage reading",
        "citation": "Copernicus Emergency Management Service GloFAS; data served by Open-Meteo.com",
    })
    manifest["terrain"].update({
        "source": "Open-Meteo elevation API (Copernicus DEM GLO-90)",
        "url": ELEVATION_URL,
        "variable": "elevation (m); slope and ruggedness derived here",
        "method": f"5-point cross sampled at +/-{TERRAIN_SAMPLE_OFFSET_DEG} deg",
        "citation": "Copernicus DEM; served by Open-Meteo.com",
    })
    manifest["_region"] = {
        "region": CFG.project.region,
        "districts": sorted(districts),
        "date_range": [start, end],
        "sampling": "point sample at district headquarters, not area-averaged",
    }

    mpath = raw / "provenance.json"
    with open(mpath, "w") as fh:
        json.dump(manifest, fh, indent=2)
    print(f"[download] wrote {mpath.name} — this is your dataset lineage, keep it")

    labels = raw / "dfo_flood_events.csv"
    if not labels.exists():
        print()
        print("=" * 70)
        print("LABELS ARE STILL MISSING — one manual step left.")
        print("=" * 70)
        print("Download the Dartmouth Flood Observatory Global Active Archive")
        print("  https://floodobservatory.colorado.edu/Archives/index.html")
        print(f"and save it as:  {labels.relative_to(ROOT)}")
        print()
        print("Then run:  python -m src.data.build_dataset")
        print("The loader expands each event into district-days; see")
        print("_load_real_labels() in src/data/loaders.py for the columns it")
        print("expects and how to adjust if DFO's format differs.")
        print("=" * 70)

    return written


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--start", default=None, help="YYYY-MM-DD")
    ap.add_argument("--end", default=None, help="YYYY-MM-DD")
    ap.add_argument("--force", action="store_true", help="refetch even if cached")
    args = ap.parse_args()
    run(start=args.start, end=args.end, force=args.force)
